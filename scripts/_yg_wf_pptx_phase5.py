def _set_text(tf, text, font_size=None, bold=None, color=None):
    tf.clear()
    p = tf.paragraphs[0]
    r = p.add_run()
    r.text = text
    if font_size: r.font.size = Pt(font_size)
    if bold is not None: r.font.bold = bold
    if color: r.font.color.rgb = color


def _write_body(tf, subhead, body_text):
    tf.clear()
    p = tf.paragraphs[0]
    if subhead:
        r = p.add_run(); r.text = subhead
        r.font.size = Pt(11); r.font.bold = True; r.font.color.rgb = NAVY
        p = tf.add_paragraph()
    r = p.add_run(); r.text = body_text
    r.font.size = Pt(9)


def fill_body_slide(slide, header_text, copy1, body1_head, body1_text, copy2, body2_head, body2_text):
    for sh in slide.shapes:
        if not sh.has_text_frame: continue
        l = Emu(sh.left).inches if sh.left else 0
        t = Emu(sh.top).inches if sh.top else 0
        txt = sh.text_frame.text.strip()
        # 헤더
        if t < 0.5 and l < 1.0:
            if header_text: _set_text(sh.text_frame, header_text, font_size=18, bold=True, color=NAVY)
        # 좌측 카피 상단 (L<1.5, 0.8<T<1.8)
        elif l < 1.5 and 0.8 < t < 1.8:
            if copy1: _set_text(sh.text_frame, copy1, font_size=9, color=GREY)
        # 좌측 카피 하단 (L<1.5, 5.5<T<6.3)
        elif l < 1.5 and 5.5 < t < 6.3:
            if copy2: _set_text(sh.text_frame, copy2, font_size=9, color=GREY)
        # 본문 상단 (L>1.5, T<2.5)
        elif l >= 1.5 and 0.5 < t < 2.5:
            if body1_head or body1_text: _write_body(sh.text_frame, body1_head, body1_text)
        # 본문 하단 (L>1.5, 5.0<T<7.0)
        elif l >= 1.5 and 5.0 < t < 7.0:
            if body2_head or body2_text: _write_body(sh.text_frame, body2_head, body2_text)


def update_page_numbers(prs):
    """모든 슬라이드 페이지 번호 갱신"""
    for i, slide in enumerate(prs.slides):
        for sh in slide.shapes:
            if not sh.has_text_frame: continue
            t = sh.text_frame.text.strip()
            l = Emu(sh.left).inches if sh.left else 0
            top = Emu(sh.top).inches if sh.top else 0
            # 페이지 번호 위치: 우측 하단 (L>7, T>11)
            if l > 7 and top > 11 and ('|' in t or t.strip().isdigit()):
                _set_text(sh.text_frame, f'|   {i+1}', font_size=9, color=GREY)


